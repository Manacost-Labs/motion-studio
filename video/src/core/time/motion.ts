// Запаздывающий слой: состояние главного слоя delay кадров назад. Тень садится на 2–4 кадра позже карты, второй план
// догоняет первый — «иерархия волочения» без симуляции. Кадр и задержка — в одних единицах (у деталей — «кадры-30», useFrame)
export const lagged = <T>(stateAt: (f: number) => T, f: number, delay: number): T => stateAt(f - delay);

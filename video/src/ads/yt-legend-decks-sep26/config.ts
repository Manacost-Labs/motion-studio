const deck = (rank: number, text: DeckText): DeckSeg => {
  const d = article.decks.find((x) => x.rank === rank);
  if (!d) throw new Error(`В article.json нет колоды №${rank}`);
  return {
    kind: 'deck',
    id: `deck-${String(rank).padStart(2, '0')}`,
    rank,
    name: d.name,
    cls: d.cls,
    mode: d.mode,
    hero: d.hero,
    code: d.code,
    list: d.list,
    poster: d.poster, // постер из api.blizzcore.ru (scripts/deck-posters.mjs)
    points: MAIN[rank],
    ...text,
  };
};

